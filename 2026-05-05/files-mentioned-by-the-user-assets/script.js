const header = document.querySelector("[data-header]");
const nav = document.querySelector("[data-nav]");
const navToggle = document.querySelector("[data-nav-toggle]");
const navLinks = Array.from(document.querySelectorAll(".site-nav a"));
const languageButtons = Array.from(document.querySelectorAll("[data-lang-switch]"));
const revealItems = Array.from(document.querySelectorAll(".reveal"));
const sections = Array.from(document.querySelectorAll("main section[id]"));
const parallaxItems = Array.from(document.querySelectorAll("[data-parallax]"));
const videos = Array.from(document.querySelectorAll("video"));
const prefersReducedMotion = window.matchMedia("(prefers-reduced-motion: reduce)").matches;

let currentLanguage = localStorage.getItem("portfolio-language") || "en";

const getText = (language, key) => {
  return key.split(".").reduce((value, part) => value?.[part], translations[language]);
};

const setLanguage = (language) => {
  currentLanguage = translations[language] ? language : "en";
  const isArabic = currentLanguage === "ar";

  document.documentElement.lang = currentLanguage;
  document.documentElement.dir = isArabic ? "rtl" : "ltr";
  document.body.dataset.lang = currentLanguage;
  document.title = translations[currentLanguage].title;
  localStorage.setItem("portfolio-language", currentLanguage);

  document.querySelectorAll("[data-i18n]").forEach((element) => {
    const value = getText(currentLanguage, element.dataset.i18n);
    if (typeof value === "string") {
      element.textContent = value;
    }
  });

  languageButtons.forEach((button) => {
    button.classList.toggle("is-active", button.dataset.langSwitch === currentLanguage);
  });

  navToggle?.setAttribute("aria-label", isArabic ? "فتح القائمة" : "Open navigation");
};

const setHeaderState = () => {
  header?.classList.toggle("is-scrolled", window.scrollY > 20);
};

const closeMobileNav = () => {
  navToggle?.setAttribute("aria-expanded", "false");
  nav?.classList.remove("is-open");
};

const playVideo = (video) => {
  const playAttempt = video.play();
  if (playAttempt && typeof playAttempt.catch === "function") {
    playAttempt.catch(() => {
      video.controls = false;
    });
  }
};

setLanguage(currentLanguage);
setHeaderState();

window.addEventListener("scroll", setHeaderState, { passive: true });

navToggle?.addEventListener("click", () => {
  const isOpen = navToggle.getAttribute("aria-expanded") === "true";
  navToggle.setAttribute("aria-expanded", String(!isOpen));
  nav?.classList.toggle("is-open", !isOpen);
});

navLinks.forEach((link) => {
  link.addEventListener("click", closeMobileNav);
});

languageButtons.forEach((button) => {
  button.addEventListener("click", () => {
    setLanguage(button.dataset.langSwitch);
    closeMobileNav();
  });
});

document.querySelectorAll("img").forEach((image) => {
  image.addEventListener("error", () => {
    const frame = image.closest(".executive-frame") || image.parentElement;
    image.hidden = true;
    frame?.classList.add("media-failed");
  });
});

videos.forEach((video) => {
  const markFailed = () => {
    video.classList.add("media-failed");
    video.closest(".city-panel, .ops-video-strip, .hero, .operations-section, .contact-section")?.classList.add("media-failed");
  };

  video.addEventListener("error", markFailed);
  video.querySelectorAll("source").forEach((source) => {
    source.addEventListener("error", markFailed);
  });
});

if ("IntersectionObserver" in window) {
  const revealObserver = new IntersectionObserver(
    (entries, observer) => {
      entries.forEach((entry) => {
        if (!entry.isIntersecting) return;
        entry.target.classList.add("is-visible");
        observer.unobserve(entry.target);
      });
    },
    {
      threshold: 0.16,
      rootMargin: "0px 0px -8% 0px"
    }
  );

  revealItems.forEach((item) => revealObserver.observe(item));

  const activeObserver = new IntersectionObserver(
    (entries) => {
      const visibleEntry = entries
        .filter((entry) => entry.isIntersecting)
        .sort((a, b) => b.intersectionRatio - a.intersectionRatio)[0];

      if (!visibleEntry) return;

      navLinks.forEach((link) => {
        link.classList.toggle("is-active", link.getAttribute("href") === `#${visibleEntry.target.id}`);
      });
    },
    {
      threshold: [0.25, 0.45, 0.65],
      rootMargin: "-18% 0px -48% 0px"
    }
  );

  sections.forEach((section) => activeObserver.observe(section));

  const videoObserver = new IntersectionObserver(
    (entries) => {
      entries.forEach((entry) => {
        const video = entry.target;
        if (video.classList.contains("media-failed")) return;
        if (entry.isIntersecting) {
          playVideo(video);
        } else {
          video.pause();
        }
      });
    },
    {
      threshold: 0.12,
      rootMargin: "180px 0px"
    }
  );

  videos.forEach((video) => videoObserver.observe(video));
} else {
  revealItems.forEach((item) => item.classList.add("is-visible"));
  videos.forEach(playVideo);
}

let ticking = false;

const updateParallax = () => {
  ticking = false;
  if (prefersReducedMotion || !parallaxItems.length) return;

  const viewportHeight = window.innerHeight || document.documentElement.clientHeight;

  parallaxItems.forEach((item) => {
    const rect = item.getBoundingClientRect();
    const progress = (rect.top + rect.height * 0.5 - viewportHeight * 0.5) / viewportHeight;
    const offset = Math.max(-34, Math.min(34, progress * -38));
    item.style.setProperty("--parallax-y", `${offset}px`);
  });
};

const requestParallax = () => {
  if (ticking) return;
  ticking = true;
  window.requestAnimationFrame(updateParallax);
};

if (!prefersReducedMotion) {
  updateParallax();
  window.addEventListener("scroll", requestParallax, { passive: true });
  window.addEventListener("resize", requestParallax);
}
